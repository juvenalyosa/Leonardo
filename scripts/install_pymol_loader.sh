#!/usr/bin/env bash
set -euo pipefail

# Install a tiny PyMOL startup loader that registers Leonardo from this source
# tree every time PyMOL starts.  This keeps the user path simple: launch PyMOL
# from the Leonardo conda environment and open Plugin > Leonardo.

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# the end-user installer points the loader at a stable path (~/.leonardo/app) that survives updates
ROOT_DIR="${LEONARDO_LOADER_ROOT:-$ROOT_DIR}"
STARTUP_DIR="${PYMOL_STARTUP_DIR:-$HOME/.pymol/startup}"
LOADER_PATH="$STARTUP_DIR/leonardo.py"
QUIET=0
DRY_RUN=0
REMOVE=0

usage() {
  cat <<'EOF'
Usage:
  ./scripts/install_pymol_loader.sh [--quiet] [--dry-run] [--remove]

Options:
  --quiet     Print only the final result
  --dry-run   Show where the loader would be written
  --remove    Remove the Leonardo startup loader
  -h, --help  Show this help
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --quiet)
      QUIET=1
      shift
      ;;
    --dry-run)
      DRY_RUN=1
      shift
      ;;
    --remove)
      REMOVE=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "ERROR: unknown argument: $1" >&2
      usage
      exit 2
      ;;
  esac
done

if [[ "$REMOVE" -eq 1 ]]; then
  if [[ "$DRY_RUN" -eq 1 ]]; then
    echo "Would remove: $LOADER_PATH"
    exit 0
  fi
  rm -f "$LOADER_PATH"
  [[ "$QUIET" -eq 1 ]] || echo "Removed PyMOL startup loader: $LOADER_PATH"
  exit 0
fi

py_root="${ROOT_DIR//\\/\\\\}"
py_root="${py_root//\"/\\\"}"

if [[ "$DRY_RUN" -eq 1 ]]; then
  echo "Would write PyMOL startup loader: $LOADER_PATH"
  echo "Leonardo source root: $ROOT_DIR"
  exit 0
fi

mkdir -p "$STARTUP_DIR"
cat > "$LOADER_PATH" <<EOF
"""PyMOL startup loader for Leonardo.

Generated by scripts/install_pymol_loader.sh.  It intentionally imports Leonardo from
the installed source tree, so updating the repository updates the plugin code
without reinstalling a ZIP through PyMOL's Plugin Manager.
"""

import os
import sys
import traceback

LEONARDO_ROOT = "$py_root"

try:
    legacy_root = os.path.join(LEONARDO_ROOT, "legacy")
    src_root = os.path.join(LEONARDO_ROOT, "src")          # the leonardo package (legacy/ modules import it)
    for source_root in (LEONARDO_ROOT, src_root, legacy_root):
        if os.path.isdir(source_root) and source_root not in sys.path:
            sys.path.insert(0, source_root)
    import ProtLigInteract

    ProtLigInteract.__init_plugin__()
    print("Leonardo startup loader: registered plugin from", LEONARDO_ROOT)
except Exception:
    print("Leonardo startup loader: failed to register plugin")
    traceback.print_exc()
EOF

# PyMOL reads plugins from ~/.pymol/startup only when ~/.pymolpluginsrc.py puts that folder on its plugin
# path, and PyMOL writes that file the first time its Plugin Manager installs something.  On a computer where
# that never happened the loader above is never read (no Plugin > Leonardo), so add the folder ourselves.
# PyMOL rewrites the file later and keeps the folder (it saves its current user plugin path).
RC_PATH="${PYMOL_PLUGINSRC:-$HOME/.pymolpluginsrc.py}"
if [[ "$STARTUP_DIR" == "$HOME/.pymol/startup" ]] && ! grep -q "Leonardo: PyMOL's user plugin folder" "$RC_PATH" 2>/dev/null; then
  cat >> "$RC_PATH" <<'RCEOF'
# Leonardo: PyMOL's user plugin folder (~/.pymol/startup), where the Leonardo loader lives
try:
  import os, pymol.plugins
  _p = os.path.expanduser('~/.pymol/startup')
  if _p not in pymol.plugins.get_startup_path(True):
    pymol.plugins.set_startup_path([_p] + pymol.plugins.get_startup_path(True), False)
except Exception:
  pass
RCEOF
fi

[[ "$QUIET" -eq 1 ]] || cat <<EOF
Installed PyMOL startup loader:
  $LOADER_PATH

Launch PyMOL from Leonardo's conda environment and open:
  Plugin > Leonardo
EOF
