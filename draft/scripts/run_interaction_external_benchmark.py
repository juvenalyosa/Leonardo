#!/usr/bin/env python3
"""Run optional external interaction-profiler checks for Leonardo.

The manuscript should not claim PLIP/ProLIF agreement unless those tools are
actually installed and executed.  This script therefore writes a status table
when dependencies are missing and writes count-level comparison tables when an
external profiler is available.
"""

from __future__ import annotations

import argparse
import csv
import importlib.util
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULTS_DIR = ROOT / "draft" / "results"


PLIP_TAG_MAP = {
    "hydrophobic_interaction": "hydrophobic",
    "hydrogen_bond": "hydrogen_bond",
    "water_bridge": "water_bridge",
    "salt_bridge": "salt_bridge",
    "pi_stack": "pi_stack",
    "pi_cation_interaction": "cation_pi",
    "halogen_bond": "halogen_bond",
    "metal_complex": "metal",
}

LEONARDO_TYPE_MAP = {
    "Hydrophobic contact": "hydrophobic",
    "Polar contact": "polar_or_hbond_candidate",
    "Salt bridge candidate": "salt_bridge",
    "vdW contact": "vdw",
}


def write_rows(path: Path, rows: list[dict], fieldnames: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def leonardo_counts(path: Path) -> Counter:
    counts: Counter = Counter()
    if not path.exists():
        return counts
    with path.open("r", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            label = LEONARDO_TYPE_MAP.get(row.get("interaction_type", ""), "other")
            counts[label] += 1
    return counts


def run_plip(pdb_path: Path, output_dir: Path) -> tuple[bool, Counter, str]:
    plipcmd = shutil.which("plipcmd") or shutil.which("plip")
    if not plipcmd:
        return False, Counter(), "PLIP executable not found on PATH."
    output_dir.mkdir(parents=True, exist_ok=True)
    cmd = [plipcmd, "-f", str(pdb_path), "-x", "-o", str(output_dir)]
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=600)
    if proc.returncode != 0:
        message = (proc.stderr or proc.stdout or "").strip().replace("\n", " ")[:500]
        return False, Counter(), f"PLIP failed with exit code {proc.returncode}: {message}"
    xml_files = sorted(output_dir.rglob("*.xml"))
    if not xml_files:
        return False, Counter(), "PLIP completed but no XML report was found."
    counts: Counter = Counter()
    for xml_path in xml_files:
        tree = ET.parse(xml_path)
        for elem in tree.iter():
            tag = elem.tag.split("}")[-1]
            label = PLIP_TAG_MAP.get(tag)
            if label:
                counts[label] += 1
    return True, counts, f"PLIP XML parsed from {xml_files[0].relative_to(ROOT)}."


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pdb", default="3PTB.pdb", help="Protein-ligand PDB file.")
    parser.add_argument(
        "--leonardo-csv",
        default="draft/results/interaction_contacts_3ptb_ben.csv",
        help="Leonardo interaction table generated by the manuscript assets script.",
    )
    parser.add_argument(
        "--out",
        default="draft/results/interaction_external_benchmark_status.csv",
        help="Output CSV with status or count-level comparison.",
    )
    parser.add_argument("--strict", action="store_true", help="Return non-zero when no external profiler is available.")
    args = parser.parse_args(argv)

    pdb_path = (ROOT / args.pdb).resolve()
    leonardo_csv = (ROOT / args.leonardo_csv).resolve()
    out_csv = (ROOT / args.out).resolve()
    plip_available = bool(shutil.which("plipcmd") or shutil.which("plip"))
    prolif_available = bool(importlib.util.find_spec("prolif"))

    if not pdb_path.exists():
        raise FileNotFoundError(pdb_path)

    l_counts = leonardo_counts(leonardo_csv)
    status_rows = []
    if plip_available:
        ok, plip_counts, note = run_plip(pdb_path, RESULTS_DIR / "plip_3ptb_ben")
        labels = sorted(set(l_counts) | set(plip_counts))
        status_rows = [
            {
                "system": pdb_path.name,
                "external_profiler": "PLIP",
                "status": "completed" if ok else "failed",
                "interaction_class": label,
                "leonardo_count": l_counts.get(label, 0),
                "external_count": plip_counts.get(label, 0),
                "note": note,
            }
            for label in labels
        ]
    else:
        status_rows = [
            {
                "system": pdb_path.name,
                "external_profiler": "PLIP/ProLIF",
                "status": "pending_dependency",
                "interaction_class": "all",
                "leonardo_count": sum(l_counts.values()),
                "external_count": "",
                "note": (
                    "Install PLIP or ProLIF before reporting external agreement. "
                    f"Detected ProLIF={prolif_available}; PLIP={plip_available}."
                ),
            }
        ]

    write_rows(
        out_csv,
        status_rows,
        [
            "system",
            "external_profiler",
            "status",
            "interaction_class",
            "leonardo_count",
            "external_count",
            "note",
        ],
    )
    if args.strict and not (plip_available or prolif_available):
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
