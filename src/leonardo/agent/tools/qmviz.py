# -- orbital labels ------------------------------------------------------------------------------ #
def resolve_orbitals(requested, homo_index):
    """'homo', 'lumo', 'homo-2', 'lumo+1' or 1-based MO numbers -> [(label, index)]."""
    out = []
    for item in list(requested or ["homo", "lumo"]):
        text = str(item).strip().lower().replace(" ", "")
        if re.fullmatch(r"\d+", text):
            idx = int(text)
            rel = idx - homo_index
            label = "HOMO" if rel == 0 else (f"HOMO{rel:+d}" if rel < 0 else ("LUMO" if rel == 1 else f"LUMO+{rel - 1}"))
            out.append((f"MO {idx} ({label})", idx))
            continue
        m = re.fullmatch(r"(homo|lumo)([+-]\d+)?", text)
        if not m:
            raise ToolError(f"unknown orbital {item!r}: use homo, lumo, homo-1, lumo+2 ... or an MO number")
        shift = int(m.group(2) or 0)
        idx = homo_index + shift if m.group(1) == "homo" else homo_index + 1 + shift
        out.append((m.group(1).upper() + (m.group(2) or ""), idx))
    return out


# -- cube files ---------------------------------------------------------------------------------- #
def grid_for(coords_ang, spacing_bohr=0.3, margin_bohr=5.0):
    xyz = np.asarray(coords_ang, dtype=float) / BOHR
    lo = xyz.min(axis=0) - margin_bohr
    hi = xyz.max(axis=0) + margin_bohr
    n = np.maximum(np.ceil((hi - lo) / spacing_bohr).astype(int) + 1, 2)
    return lo, float(spacing_bohr), n


def grid_points(lo, h, n):
    ax = [lo[i] + h * np.arange(n[i]) for i in range(3)]
    X, Y, Z = np.meshgrid(ax[0], ax[1], ax[2], indexing="ij")
    return np.stack([X.ravel(), Y.ravel(), Z.ravel()], axis=1)


def write_cube(path, symbols, coords_ang, lo, h, n, values, comment="Leonardo"):
    values = np.asarray(values, dtype=float).reshape(int(n[0]), int(n[1]), int(n[2]))
    xyz = np.asarray(coords_ang, dtype=float) / BOHR
    with open(path, "w") as fh:
        fh.write(f"{comment}\nGenerated by Leonardo AI (cube, bohr)\n")
        fh.write(f"{len(symbols):5d} {lo[0]:12.6f} {lo[1]:12.6f} {lo[2]:12.6f}\n")
        fh.write(f"{int(n[0]):5d} {h:12.6f} {0.0:12.6f} {0.0:12.6f}\n")
        fh.write(f"{int(n[1]):5d} {0.0:12.6f} {h:12.6f} {0.0:12.6f}\n")
        fh.write(f"{int(n[2]):5d} {0.0:12.6f} {0.0:12.6f} {h:12.6f}\n")
        for s, (x, y, z) in zip(symbols, xyz):
            zn = _Z.get(str(s).capitalize(), 0)
            fh.write(f"{zn:5d} {float(zn):12.6f} {x:12.6f} {y:12.6f} {z:12.6f}\n")
        flat = values.reshape(int(n[0]) * int(n[1]), int(n[2]))
        for row in flat:
            for k in range(0, len(row), 6):
                fh.write(" ".join(f"{v:13.5E}" for v in row[k:k + 6]) + "\n")
    return path


def read_cube_values(path):
    """Grid values of a Gaussian cube file (flat, same order as written)."""
    with open(path) as fh:
        fh.readline()
        fh.readline()
        natoms = abs(int(fh.readline().split()[0]))
        dims = [abs(int(fh.readline().split()[0])) for _ in range(3)]
        for _ in range(natoms):
            fh.readline()
        vals = np.array(fh.read().split(), dtype=float)
    return vals[: dims[0] * dims[1] * dims[2]]


# -- Slater-type orbitals (MOPAC) ---------------------------------------------------------------- #
def _sto(pts_bohr, center_bohr, zeta, pqn, kind):
    d = pts_bohr - center_bohr
    x, y, z = d[:, 0], d[:, 1], d[:, 2]
    r = np.sqrt(x * x + y * y + z * z) + 1e-12
    norm = (2.0 * zeta) ** (pqn + 0.5) / math.sqrt(math.factorial(2 * pqn))
    radial = norm * r ** (pqn - 1) * np.exp(-zeta * r)
    k = kind.upper()
    if k == "S":
        ang = 1.0 / math.sqrt(4 * math.pi)
    elif k in ("PX", "PY", "PZ"):
        ang = math.sqrt(3 / (4 * math.pi)) * {"PX": x, "PY": y, "PZ": z}[k] / r
    elif k in ("X2", "DX2"):
        ang = math.sqrt(15 / (16 * math.pi)) * (x * x - y * y) / (r * r)
    elif k in ("Z2", "DZ2"):
        ang = math.sqrt(5 / (16 * math.pi)) * (3 * z * z - r * r) / (r * r)
    elif k in ("XZ", "DXZ"):
        ang = math.sqrt(15 / (4 * math.pi)) * x * z / (r * r)
    elif k in ("YZ", "DYZ"):
        ang = math.sqrt(15 / (4 * math.pi)) * y * z / (r * r)
    elif k in ("XY", "DXY"):
        ang = math.sqrt(15 / (4 * math.pi)) * x * y / (r * r)
    else:
        raise ToolError(f"unsupported atomic orbital type {kind!r}")
    return radial * ang


def sto_grid_values(basis, coeff_rows, coords_ang, lo, h, n, occupations=None):
    """MO values (one per row of ``coeff_rows``) and, with occupations, the valence density on a grid."""
    pts = grid_points(lo, h, n)
    xyz = np.asarray(coords_ang, dtype=float) / BOHR
    mos = np.zeros((len(coeff_rows), pts.shape[0]))
    for mu, (atom, kind, zeta, pqn) in enumerate(basis):
        phi = _sto(pts, xyz[atom], zeta, pqn, kind)
        for i, row in enumerate(coeff_rows):
            c = row[mu]
            if c:
                mos[i] += c * phi
    density = None
    if occupations is not None:
        density = np.einsum("i,ij->j", np.asarray(occupations, dtype=float), mos * mos)
    return mos, density


# -- PyMOL display ------------------------------------------------------------------------------- #
def show_orbital_cube(cube_path, name, isovalue=0.03, parent=""):
    cmd = _cmd()
    cmap = f"{name}_map"
    for o in (cmap, f"{name}_pos", f"{name}_neg"):
        if o in cmd.get_names("all"):
            cmd.delete(o)
    cmd.load(cube_path, cmap)
    cmd.isosurface(f"{name}_pos", cmap, float(isovalue))
    cmd.isosurface(f"{name}_neg", cmap, -float(isovalue))
    cmd.color("blue", f"{name}_pos")
    cmd.color("red", f"{name}_neg")
    for o in (f"{name}_pos", f"{name}_neg"):
        cmd.set("transparency", 0.3, o)
    cmd.disable(cmap)
    try:
        cmd.group(f"{parent or 'QM'}.orbitals", f"{cmap} {name}_pos {name}_neg")
    except Exception:
        pass
    return [f"{name}_pos", f"{name}_neg"]


def surface_esp_range(density, esp, density_iso=0.002):
    """ESP values near the density isosurface (2nd-98th percentile): a charged molecule is positive (or
    negative) everywhere, so a symmetric fixed scale would paint it one color."""
    d = np.asarray(density, dtype=float)
    v = np.asarray(esp, dtype=float)
    near = (d > 0.8 * density_iso) & (d < 1.25 * density_iso)
    if near.sum() < 20:
        return None
    lo, hi = np.percentile(v[near], [2, 98])
    return float(lo), float(hi)


def show_esp_surface(density_cube, esp_cube, name, density_iso=0.002, esp_range=0.06, esp_limits=None):
    cmd = _cmd()
    dmap, emap, surf, ramp = f"{name}_dens", f"{name}_esp", f"{name}_surf", f"{name}_ramp"
    for o in (dmap, emap, surf, ramp):
        if o in cmd.get_names("all"):
            cmd.delete(o)
    cmd.load(density_cube, dmap)
    cmd.load(esp_cube, emap)
    cmd.isosurface(surf, dmap, float(density_iso))
    if esp_limits:
        lo, hi = esp_limits
        levels = [lo, 0.5 * (lo + hi), hi]
    else:
        levels = [-float(esp_range), 0.0, float(esp_range)]
    cmd.ramp_new(ramp, emap, levels, ["red", "white", "blue"])
    cmd.set("surface_color", ramp, surf)
    cmd.set("transparency", 0.25, surf)
    cmd.disable(dmap)
    cmd.disable(emap)
    return [surf, ramp]


def esp_from_charges(symbols, coords_ang, charges, lo, h, n):
    """Electrostatic potential (a.u.) of point charges on the grid (a fitted-charge ESP, not the QM one)."""
    pts = grid_points(lo, h, n)
    xyz = np.asarray(coords_ang, dtype=float) / BOHR
    v = np.zeros(pts.shape[0])
    for q, c in zip(charges, xyz):
        r = np.linalg.norm(pts - c, axis=1)
        v += float(q) / np.maximum(r, 0.3)
    return v


def frame(obj):
    cmd = _cmd()
    try:
        from .. import presentation

        keep = [n for n in cmd.get_names("objects") if n.lower().startswith(("psi4", "mopac", "qm"))]
        presentation.declutter(keep=keep + ([obj] if obj else []))
        cmd.hide("labels", "dock_*")
    except Exception:
        pass
    if obj and obj in cmd.get_names("objects"):
        cmd.orient(obj)
        cmd.zoom(obj, 4.0, complete=1)


def load_molecule(symbols, coords_ang, name):
    """A small molecule as a PyMOL object (element + coordinates; bonds from distances)."""
    cmd = _cmd()
    lines = [str(len(symbols)), name]
    lines += [f"{s} {x:.6f} {y:.6f} {z:.6f}" for s, (x, y, z) in zip(symbols, coords_ang)]
    if name in cmd.get_names("objects"):
        cmd.delete(name)
    cmd.load_raw("\n".join(lines) + "\n", "xyz", name)
    cmd.show_as("sticks", name)
    cmd.set("stick_radius", 0.16, name)
    cmd.show("spheres", name)
    cmd.set("sphere_scale", 0.22, name)
    cmd.util.cbag(name)
    return name


def animate_mode(symbols, coords_ang, mode_vec, name, amplitude=0.25, n_frames=24):
    """Multi-state object oscillating along a normal mode (Å displacements, any normalization)."""
    cmd = _cmd()
    base = np.asarray(coords_ang, dtype=float)
    mode = np.asarray(mode_vec, dtype=float).reshape(base.shape)
    mode = mode / max(np.abs(mode).max(), 1e-9)
    if name in cmd.get_names("objects"):
        cmd.delete(name)
    for k in range(n_frames):
        disp = base + float(amplitude) * math.sin(2 * math.pi * k / n_frames) * mode
        lines = [str(len(symbols)), name] + [f"{s} {x:.6f} {y:.6f} {z:.6f}" for s, (x, y, z) in zip(symbols, disp)]
        cmd.load_raw("\n".join(lines) + "\n", "xyz", name, state=k + 1)
    cmd.show_as("sticks", name)
    cmd.util.cbag(name)
    cmd.frame(1)
    cmd.mplay()
    return name


def kabsch(P, Q):
    """Rotation R and translation t with R @ p + t ≈ q (least squares)."""
    P = np.asarray(P, dtype=float)
    Q = np.asarray(Q, dtype=float)
    pc, qc = P.mean(axis=0), Q.mean(axis=0)
    H = (P - pc).T @ (Q - qc)
    U, _S, Vt = np.linalg.svd(H)
    d = np.sign(np.linalg.det(Vt.T @ U.T))
    D = np.diag([1.0, 1.0, d])
    R = Vt.T @ D @ U.T
    return R, qc - R @ pc


