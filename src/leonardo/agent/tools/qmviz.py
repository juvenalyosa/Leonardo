def _figure(width=7.2, height=3.6):
    from matplotlib.backends.backend_agg import FigureCanvasAgg
    from matplotlib.figure import Figure

    fig = Figure(figsize=(width, height), dpi=110)
    FigureCanvasAgg(fig)
    return fig


def ir_png(freqs_cm, intensities, path, title, fwhm=18.0, intensity_label="IR intensity (km/mol)"):
    f = np.asarray(freqs_cm, dtype=float)
    y = np.asarray(intensities, dtype=float)
    keep = f > 10.0
    f, y = f[keep], y[keep]
    fig = _figure()
    ax = fig.add_subplot(111)
    ax.vlines(f, 0, y, color="#1f77b4", linewidth=1.3)
    lo, hi = max(0.0, f.min() - 200) if f.size else 0.0, (f.max() + 200) if f.size else 4000.0
    grid = np.linspace(lo, hi, 3000)
    band = np.zeros_like(grid)
    sigma = fwhm / 2.3548
    for fi, yi in zip(f, y):
        band += yi * np.exp(-0.5 * ((grid - fi) / sigma) ** 2)
    if band.max() > 0:
        ax2 = ax.twinx()
        ax2.plot(grid, 100 * band / band.max(), color="#2ca02c", linewidth=1.4)
        ax2.fill_between(grid, 0, 100 * band / band.max(), color="#2ca02c", alpha=0.15)
        ax2.set_ylabel("Relative absorbance (%)")
        ax2.set_ylim(bottom=0)
    for i in np.argsort(y)[::-1][:4]:
        ax.annotate(f"{f[i]:.0f}", (f[i], y[i]), textcoords="offset points", xytext=(0, 3), ha="center", fontsize=8)
    ax.set_xlim(hi, lo)
    ax.set_xlabel("Wavenumber (cm$^{-1}$)")
    ax.set_ylabel(intensity_label)
    ax.set_title(title, fontsize=10)
    ax.grid(alpha=0.25)
    fig.tight_layout()
    fig.savefig(path)
    return path


def uv_png(energies_ev, strengths, path, title, sigma_ev=0.25, strength_label="Oscillator strength"):
    e = np.asarray(energies_ev, dtype=float)
    s = np.asarray(strengths, dtype=float)
    keep = e > 0
    e, s = e[keep], s[keep]
    lam = EV_NM / e
    fig = _figure()
    ax = fig.add_subplot(111)
    ax.vlines(lam, 0, s, color="#6a3d9a", linewidth=1.5)
    lo_nm = max(100.0, float(lam.min()) - 40) if lam.size else 150.0
    hi_nm = float(lam.max()) + 80 if lam.size else 600.0
    grid_nm = np.linspace(lo_nm, hi_nm, 2000)
    grid_ev = EV_NM / grid_nm
    band = np.zeros_like(grid_nm)
    for ei, si in zip(e, s):
        band += si * np.exp(-0.5 * ((grid_ev - ei) / sigma_ev) ** 2)
    if band.max() > 0:
        ax2 = ax.twinx()
        ax2.plot(grid_nm, band / band.max(), color="#e6550d", linewidth=1.5)
        ax2.fill_between(grid_nm, 0, band / band.max(), color="#e6550d", alpha=0.15)
        ax2.set_ylabel("Relative absorbance")
        ax2.set_ylim(bottom=0)
    for i in np.argsort(s)[::-1][:3]:
        if s[i] > 0:
            ax.annotate(f"{lam[i]:.0f} nm", (lam[i], s[i]), textcoords="offset points", xytext=(0, 3), ha="center",
                        fontsize=8)
    ax.set_xlim(lo_nm, hi_nm)
    ax.set_xlabel("Wavelength (nm)")
    ax.set_ylabel(strength_label)
    ax.set_title(title, fontsize=10)
    ax.grid(alpha=0.25)
    fig.tight_layout()
    fig.savefig(path)
    return path


