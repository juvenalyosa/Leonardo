def write_markdown_report(path, summary, mode_rows):
    s = dict(summary or {})
    init_m = dict(s.get("initial_metrics", {}) or {})
    ref_m = dict(s.get("refined_metrics", {}) or {})
    scales = dict(s.get("best_scales", {}) or {})
    typed = dict(s.get("selected_typed_parameters", {}) or {})
    rows = list(mode_rows or [])
    lines = []
    lines.append("# Ligand QM-to-FF Vibrational Refinement")
    lines.append("")
    lines.append("## QM Reference")
    lines.append("")
    lines.append(f"- Method: `{str(s.get('qm_method', '') or '')}`")
    lines.append(f"- Basis: `{str(s.get('qm_basis', '') or '')}`")
    lines.append(f"- Stationary point without imaginary frequencies: `{bool(s.get('stationary_point_ok', False))}`")
    lines.append(f"- QM vibrational modes used: `{int(s.get('qm_vibrational_mode_count', 0) or 0)}`")
    lines.append(f"- Fit mode: `{str(s.get('fit_mode', 'global') or 'global')}`")
    lines.append("")
    lines.append("## Statistics")
    lines.append("")
    lines.append("| Metric | Initial FF | Refined FF |")
    lines.append("| --- | ---: | ---: |")
    for key, label in (
        ("objective", "Objective"),
        ("freq_rmse_cm", "Frequency RMSE (cm^-1)"),
        ("freq_mae_cm", "Frequency MAE (cm^-1)"),
        ("ir_rmse_norm", "IR RMSE (norm)"),
        ("geom_rmsd_ang", "Geometry RMSD (A)"),
    ):
        lines.append(
            f"| {label} | {float(init_m.get(key, float('nan'))):.3f} | {float(ref_m.get(key, float('nan'))):.3f} |"
        )
    lines.append("")
    lines.append("## Best Scale Factors")
    lines.append("")
    for name in sorted(scales):
        lines.append(f"- `{name}` = `{float(scales[name]):.4f}`")
    lines.append("")
    if any(list(typed.values())):
        lines.append("## Typed Groups")
        lines.append("")
        for cat in ("bond", "angle", "torsion", "sigma", "epsilon"):
            group_rows = list(typed.get(cat, []) or [])
            if not group_rows:
                continue
            labels = [f"{' '.join([str(x) for x in row.get('key', [])])} (n={int(row.get('count', 0) or 0)})" for row in group_rows]
            lines.append(f"- `{cat}`: " + ", ".join(labels))
        lines.append("")
    lines.append("## Leading Mode Errors")
    lines.append("")
    lines.append("| Mode | QM | Initial | Refined | |d Initial| | |d Refined| |")
    lines.append("| --- | ---: | ---: | ---: | ---: | ---: |")
    for row in rows[: min(12, len(rows))]:
        lines.append(
            f"| {int(row['mode_rank'])} | {float(row['qm_freq_cm']):.1f} | {float(row['ff_initial_freq_cm']):.1f} | "
            f"{float(row['ff_refined_freq_cm']):.1f} | {float(row['ff_initial_abs_error_cm']):.1f} | {float(row['ff_refined_abs_error_cm']):.1f} |"
        )
    lines.append("")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


def make_summary_plots(out_png, summary, mode_rows, qm_ir_grid, qm_ir_curve, base_ir_curve, refined_ir_curve):
    import matplotlib.pyplot as plt

    rows = list(mode_rows or [])
    qm = np.asarray([float(r["qm_freq_cm"]) for r in rows], dtype=float)
    ff0 = np.asarray([float(r["ff_initial_freq_cm"]) for r in rows], dtype=float)
    ff1 = np.asarray([float(r["ff_refined_freq_cm"]) for r in rows], dtype=float)
    err0 = np.asarray([float(r["ff_initial_abs_error_cm"]) for r in rows], dtype=float)
    err1 = np.asarray([float(r["ff_refined_abs_error_cm"]) for r in rows], dtype=float)
    grid = np.asarray(qm_ir_grid, dtype=float)
    qm_ir = np.asarray(qm_ir_curve, dtype=float)
    mm0_ir = np.asarray(base_ir_curve, dtype=float)
    mm1_ir = np.asarray(refined_ir_curve, dtype=float)
    scales = dict((summary or {}).get("best_scales", {}) or {})
    history = np.asarray(list((summary or {}).get("pso_history", []) or []), dtype=float)
    plt.style.use("default")
    fig, axes = plt.subplots(2, 2, figsize=(12.5, 9.5), dpi=150)
    ax = axes[0, 0]
    if qm.size:
        lo = float(min(np.min(qm), np.min(ff0), np.min(ff1)) - 50.0)
        hi = float(max(np.max(qm), np.max(ff0), np.max(ff1)) + 50.0)
        ax.plot([lo, hi], [lo, hi], color="#7a7a7a", lw=1.2, ls="--")
        ax.scatter(qm, ff0, s=30, color="#cc6677", alpha=0.75, label="Template FF")
        ax.scatter(qm, ff1, s=30, color="#117733", alpha=0.75, label="Refined FF")
        ax.set_xlim(lo, hi)
        ax.set_ylim(lo, hi)
    ax.set_title("QM vs FF Frequencies")
    ax.set_xlabel("QM frequency (cm$^{-1}$)")
    ax.set_ylabel("FF frequency (cm$^{-1}$)")
    ax.legend(frameon=False, loc="best")
    ax = axes[0, 1]
    if err0.size:
        idx = np.arange(err0.size)
        ax.plot(idx, err0, color="#cc6677", lw=1.6, label="Template FF")
        ax.plot(idx, err1, color="#117733", lw=1.6, label="Refined FF")
    ax.set_title("Mode Absolute Error")
    ax.set_xlabel("Mode rank")
    ax.set_ylabel("|error| (cm$^{-1}$)")
    ax.legend(frameon=False, loc="best")
    ax = axes[1, 0]
    if grid.size:
        ax.plot(grid, qm_ir, color="#332288", lw=1.8, label="QM")
        ax.plot(grid, mm0_ir, color="#cc6677", lw=1.6, label="Template FF")
        ax.plot(grid, mm1_ir, color="#117733", lw=1.6, label="Refined FF")
    ax.set_title("IR Spectrum Overlay")
    ax.set_xlabel("Wavenumber (cm$^{-1}$)")
    ax.set_ylabel("Normalized intensity")
    ax.legend(frameon=False, loc="upper right")
    ax.invert_xaxis()
    ax = axes[1, 1]
    names = list(sorted(scales))
    vals = np.asarray([float(scales[k]) for k in names], dtype=float)
    xpos = np.arange(len(names), dtype=int)
    ax.bar(xpos, vals, color="#44aa99", alpha=0.85, width=0.65)
    ax.axhline(1.0, color="#7a7a7a", lw=1.1, ls="--")
    ax.set_xticks(xpos)
    ax.set_xticklabels(names, rotation=25, ha="right")
    ax.set_ylabel("Scale factor")
    ax.set_title("Refined Parameter Scales")
    if history.size:
        twin = ax.twinx()
        twin.plot(np.arange(history.size), history, color="#ddaa33", lw=1.8, marker="o", ms=3.5)
        twin.set_ylabel("PSO objective")
    fig.tight_layout()
    fig.savefig(out_png, bbox_inches="tight")
    plt.close(fig)


