def _load_openmm():
    import openmm as omm
    from openmm import app, unit

    return omm, app, unit


def _quantity_to_float(val, target_unit):
    return float(val.value_in_unit(target_unit))


def _bond_set_from_mol2_bonds(bonds):
    out = set()
    for bond in list(bonds or []):
        a1 = _safe_int(bond.get("a1", 0), default=0) - 1
        a2 = _safe_int(bond.get("a2", 0), default=0) - 1
        if a1 < 0 or a2 < 0 or a1 == a2:
            continue
        out.add((min(a1, a2), max(a1, a2)))
    return out


def _typed_multiplier(scales, category, key):
    name = _typed_scale_param_name(category, key)
    return _safe_float(scales.get(name, 1.0), default=1.0)


def _pair_scale(scales, atom_types, i, j, category):
    at_i = str(atom_types[int(i)]) if int(i) < len(atom_types) else ""
    at_j = str(atom_types[int(j)]) if int(j) < len(atom_types) else ""
    si = _typed_multiplier(scales, category, at_i)
    sj = _typed_multiplier(scales, category, at_j)
    return float(math.sqrt(max(1.0e-12, si * sj)))


def _apply_scales_to_openmm_system(system, scales, typed_plan=None):
    omm, _, unit = _load_openmm()
    bond_scale = _safe_float(scales.get("bond_k_scale", 1.0), default=1.0)
    angle_scale = _safe_float(scales.get("angle_k_scale", 1.0), default=1.0)
    torsion_scale = _safe_float(scales.get("torsion_k_scale", 1.0), default=1.0)
    sigma_scale = _safe_float(scales.get("sigma_scale", 1.0), default=1.0)
    epsilon_scale = _safe_float(scales.get("epsilon_scale", 1.0), default=1.0)
    plan = dict(typed_plan or {})
    atom_types = [str(x) for x in list(plan.get("atom_types", []) or [])]
    bond_types_by_index = list(plan.get("bond_types_by_index", []) or [])
    angle_types_by_index = list(plan.get("angle_types_by_index", []) or [])
    torsion_types_by_index = list(plan.get("torsion_types_by_index", []) or [])
    for force in system.getForces():
        if isinstance(force, omm.HarmonicBondForce):
            for i in range(force.getNumBonds()):
                a, b, length, kval = force.getBondParameters(i)
                typed = _typed_multiplier(scales, "bond", bond_types_by_index[i]) if i < len(bond_types_by_index) else 1.0
                force.setBondParameters(i, a, b, length, kval * bond_scale * typed)
        elif isinstance(force, omm.HarmonicAngleForce):
            for i in range(force.getNumAngles()):
                a, b, c, theta, kval = force.getAngleParameters(i)
                typed = _typed_multiplier(scales, "angle", angle_types_by_index[i]) if i < len(angle_types_by_index) else 1.0
                force.setAngleParameters(i, a, b, c, theta, kval * angle_scale * typed)
        elif isinstance(force, omm.PeriodicTorsionForce):
            for i in range(force.getNumTorsions()):
                a, b, c, d, periodicity, phase, kval = force.getTorsionParameters(i)
                typed = _typed_multiplier(scales, "torsion", torsion_types_by_index[i]) if i < len(torsion_types_by_index) else 1.0
                force.setTorsionParameters(i, a, b, c, d, periodicity, phase, kval * torsion_scale * typed)
        elif isinstance(force, omm.NonbondedForce):
            for i in range(force.getNumParticles()):
                q, sigma, eps = force.getParticleParameters(i)
                atype = str(atom_types[i]) if i < len(atom_types) else ""
                sigma_typed = _typed_multiplier(scales, "sigma", atype)
                epsilon_typed = _typed_multiplier(scales, "epsilon", atype)
                sigma_nm = max(1.0e-8, _quantity_to_float(sigma, unit.nanometer) * sigma_scale * sigma_typed)
                eps_kj = max(0.0, _quantity_to_float(eps, unit.kilojoule_per_mole) * epsilon_scale * epsilon_typed)
                force.setParticleParameters(
                    i,
                    q,
                    sigma_nm * unit.nanometer,
                    eps_kj * unit.kilojoule_per_mole,
                )
            for i in range(force.getNumExceptions()):
                a, b, qprod, sigma, eps = force.getExceptionParameters(i)
                sigma_pair = _pair_scale(scales, atom_types, a, b, "sigma")
                epsilon_pair = _pair_scale(scales, atom_types, a, b, "epsilon")
                sigma_nm = max(1.0e-8, _quantity_to_float(sigma, unit.nanometer) * sigma_scale * sigma_pair)
                eps_kj = max(0.0, _quantity_to_float(eps, unit.kilojoule_per_mole) * epsilon_scale * epsilon_pair)
                force.setExceptionParameters(
                    i,
                    a,
                    b,
                    qprod,
                    sigma_nm * unit.nanometer,
                    eps_kj * unit.kilojoule_per_mole,
                )
    return system


