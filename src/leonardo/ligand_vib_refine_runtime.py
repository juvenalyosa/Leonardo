def _collect_frequency_payload(psi4_mod, wfn, nat):
    payload = {}
    try:
        fa = getattr(wfn, "frequency_analysis", None)
        if not isinstance(fa, dict):
            return payload
        omega = _datum_data(fa.get("omega"))
        ir = _datum_data(fa.get("IR_intensity"))
        trv = _datum_data(fa.get("TRV"))
        if omega is not None:
            omega = np.asarray(omega).reshape(-1)
            payload["freq_cm_real"] = [float(np.real(v)) for v in omega.tolist()]
            payload["freq_cm_imag"] = [float(np.imag(v)) for v in omega.tolist()]
        if ir is not None:
            ir = np.asarray(ir, dtype=float).reshape(-1)
            payload["ir_intensity_km_mol"] = [float(v) for v in ir.tolist()]
        if trv is not None:
            trv = np.asarray(trv).reshape(-1)
            payload["freq_trv"] = [str(v) for v in trv.tolist()]
        x = _datum_data(fa.get("x"))
        if x is not None:
            x = np.asarray(x, dtype=float)
            if x.ndim == 2 and int(x.shape[0]) == int(3 * int(nat)):
                nm = int(x.shape[1])
                mode_cart_bohr = np.zeros((nm, int(nat), 3), dtype=float)
                for mi in range(nm):
                    mode_cart_bohr[mi, :, :] = x[:, mi].reshape(int(nat), 3)
                payload["_mode_cart_ang"] = mode_cart_bohr * float(psi4_mod.constants.bohr2angstroms)
    except Exception:
        pass
    return payload


def _parse_opt_return(ret):
    energy = None
    wfn = None
    hist = None
    if isinstance(ret, tuple):
        if len(ret) >= 1:
            energy = ret[0]
        for item in ret[1:]:
            if isinstance(item, dict):
                hist = item
            else:
                try:
                    if hasattr(item, "variables"):
                        wfn = item
                except Exception:
                    pass
    else:
        energy = ret
    return energy, wfn, hist


def load_mol2_full_records(mol2_file):
    records = []
    bonds = []
    path = str(mol2_file or "").strip()
    if (not path) or (not os.path.isfile(path)):
        return {"atoms": [], "bonds": [], "residue_name": "LIG"}
    section = None
    residue_name = "LIG"
    with open(path, "r", encoding="utf-8", errors="ignore") as fh:
        for raw in fh:
            line = str(raw).rstrip("\n")
            if not line.strip():
                continue
            if line.startswith("@<TRIPOS>"):
                section = line.strip().upper()
                continue
            if section == "@<TRIPOS>MOLECULE":
                if residue_name == "LIG":
                    residue_name = str(line.strip() or "LIG")
                continue
            if section == "@<TRIPOS>ATOM":
                parts = line.split()
                if len(parts) < 9:
                    continue
                atom_id = _safe_int(parts[0], default=0)
                atom_name = str(parts[1]).strip() or f"A{atom_id}"
                x = _safe_float(parts[2])
                y = _safe_float(parts[3])
                z = _safe_float(parts[4])
                atom_type = str(parts[5]).strip() or "c3"
                sub_id = _safe_int(parts[6], default=1)
                sub_name = str(parts[7]).strip() or residue_name
                charge = _safe_float(parts[8])
                elem = str(_infer_element_from_mol2_name_type(atom_name, atom_type) or "C").strip().upper() or "C"
                residue_name = str(sub_name or residue_name)
                records.append(
                    {
                        "id": int(atom_id),
                        "name": str(atom_name),
                        "x": float(x),
                        "y": float(y),
                        "z": float(z),
                        "type": str(atom_type),
                        "sub_id": int(sub_id),
                        "sub_name": str(sub_name),
                        "charge": float(charge),
                        "element": str(elem),
                    }
                )
            elif section == "@<TRIPOS>BOND":
                parts = line.split()
                if len(parts) < 4:
                    continue
                bonds.append(
                    {
                        "id": _safe_int(parts[0], default=len(bonds) + 1),
                        "a1": _safe_int(parts[1], default=0),
                        "a2": _safe_int(parts[2], default=0),
                        "order": str(parts[3]).strip(),
                    }
                )
    records.sort(key=lambda row: int(row["id"]))
    return {"atoms": records, "bonds": bonds, "residue_name": str(residue_name or "LIG")}


def _normalize_element_symbol(symbol):
    txt = str(symbol or "").strip()
    if not txt:
        return ""
    if len(txt) == 1:
        return txt.upper()
    return txt[:1].upper() + txt[1:].lower()


def load_first_sdf_record_atoms(sdf_file):
    path = str(sdf_file or "").strip()
    if (not path) or (not os.path.isfile(path)):
        return {"name": "", "atoms": []}
    text = open(path, "r", encoding="utf-8", errors="ignore").read()
    blocks = text.split("$$$$")
    for raw in blocks:
        block = str(raw).strip("\n\r\t ")
        if not block:
            continue
        lines = block.splitlines()
        if len(lines) < 4:
            continue
        counts_idx = None
        counts = ""
        for idx, line in enumerate(lines[:12]):
            txt = str(line or "").rstrip()
            if ("V2000" in txt.upper()) or ("V3000" in txt.upper()):
                counts_idx = int(idx)
                counts = txt
                break
            parts = txt.split()
            if len(parts) >= 2 and str(parts[0]).strip().isdigit() and str(parts[1]).strip().isdigit():
                counts_idx = int(idx)
                counts = txt
                break
        if counts_idx is None:
            continue
        if "V3000" in counts.upper():
            raise ValueError("V3000 SDF input is not supported yet for QM start geometry")
        try:
            n_atoms = int(counts[0:3])
        except Exception:
            parts = counts.split()
            if not parts:
                continue
            n_atoms = _safe_int(parts[0], default=0)
        if n_atoms <= 0:
            continue
        start = int(counts_idx) + 1
        stop = start + int(n_atoms)
        if len(lines) < stop:
            continue
        atoms = []
        for idx, line in enumerate(lines[start:stop], start=1):
            try:
                x = float(line[0:10])
                y = float(line[10:20])
                z = float(line[20:30])
                symbol = str(line[31:34]).strip()
            except Exception:
                parts = line.split()
                if len(parts) < 4:
                    atoms = []
                    break
                x = _safe_float(parts[0])
                y = _safe_float(parts[1])
                z = _safe_float(parts[2])
                symbol = str(parts[3]).strip()
            atoms.append(
                {
                    "index": int(idx),
                    "name": f"{_normalize_element_symbol(symbol) or 'X'}{int(idx)}",
                    "element": _normalize_element_symbol(symbol) or "C",
                    "symbol": _normalize_element_symbol(symbol) or "C",
                    "x": float(x),
                    "y": float(y),
                    "z": float(z),
                }
            )
        if atoms:
            title = ""
            for line in lines[: int(counts_idx)]:
                if str(line or "").strip():
                    title = str(line).strip()
                    break
            return {"name": str(title or "LIG"), "atoms": atoms}
    return {"name": "", "atoms": []}


def validate_qm_start_sdf_matches_template_mol2(sdf_file, mol2_file):
    sdf_payload = load_first_sdf_record_atoms(sdf_file)
    mol2_payload = load_mol2_full_records(mol2_file)
    sdf_atoms = list(sdf_payload.get("atoms", []) or [])
    mol2_atoms = list(mol2_payload.get("atoms", []) or [])
    if not sdf_atoms:
        raise ValueError(f"`--qm-start-sdf` does not contain any readable SDF atoms: {sdf_file}")
    if not mol2_atoms:
        raise ValueError(f"`--mol2` does not contain any readable MOL2 atoms: {mol2_file}")
    if len(sdf_atoms) != len(mol2_atoms):
        raise ValueError(
            f"`--qm-start-sdf` atom count ({len(sdf_atoms)}) does not match template `--mol2` atom count ({len(mol2_atoms)})."
        )
    mismatches = []
    for idx, (sdf_atom, mol2_atom) in enumerate(zip(sdf_atoms, mol2_atoms), start=1):
        sdf_el = _normalize_element_symbol(sdf_atom.get("element", ""))
        mol2_el = _normalize_element_symbol(mol2_atom.get("element", ""))
        if sdf_el != mol2_el:
            mismatches.append((idx, sdf_el, mol2_el, str(mol2_atom.get("name", ""))))
            if len(mismatches) >= 5:
                break
    if mismatches:
        details = "; ".join(
            f"atom {idx}: sdf={sdf_el or '?'} mol2={mol2_el or '?'} ({name or 'unnamed'})"
            for idx, sdf_el, mol2_el, name in mismatches
        )
        raise ValueError(
            "`--qm-start-sdf` atom ordering does not match template `--mol2`. "
            "Use an SDF with the same atom order as the parameterized ligand or remap it first. "
            f"First mismatches: {details}"
        )
    return {
        "ok": True,
        "name": str(sdf_payload.get("name", "") or "LIG"),
        "atom_count": int(len(sdf_atoms)),
        "atom_symbols": [str(_normalize_element_symbol(a.get('element', '')) or 'C') for a in sdf_atoms],
    }


def write_mol2_with_coords(template_mol2, coords_ang, out_mol2):
    payload = load_mol2_full_records(template_mol2)
    atoms = list(payload.get("atoms", []) or [])
    coords = np.asarray(coords_ang, dtype=float)
    if coords.ndim != 2 or coords.shape[1] != 3:
        raise ValueError("coords_ang must be shaped (n_atoms, 3)")
    if int(coords.shape[0]) != int(len(atoms)):
        raise ValueError("Atom count mismatch for MOL2 coordinate write")
    out_lines = []
    section = None
    idx = 0
    with open(template_mol2, "r", encoding="utf-8", errors="ignore") as fh:
        for raw in fh:
            line = str(raw).rstrip("\n")
            if line.startswith("@<TRIPOS>"):
                section = line.strip().upper()
                out_lines.append(line)
                continue
            if section == "@<TRIPOS>ATOM" and line.strip():
                atom = atoms[idx]
                x, y, z = coords[idx]
                newline = (
                    f"{int(atom['id']):7d} {str(atom['name']):<8} "
                    f"{float(x):10.4f} {float(y):10.4f} {float(z):10.4f} "
                    f"{str(atom['type']):<8} {int(atom['sub_id']):4d} {str(atom['sub_name']):<8} "
                    f"{float(atom['charge']):10.6f}"
                )
                out_lines.append(newline)
                idx += 1
                continue
            out_lines.append(line)
    with open(out_mol2, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out_lines) + "\n")


def build_psi4_molecule_block_from_atoms(atoms, charge=0, multiplicity=1):
    lines = [f"{int(charge)} {int(max(1, multiplicity))}"]
    for atom in list(atoms or []):
        sym = str(psi4_element_token(atom.get("element", atom.get("symbol", "C"))) or "C")
        x = _safe_float(atom.get("x", 0.0))
        y = _safe_float(atom.get("y", 0.0))
        z = _safe_float(atom.get("z", 0.0))
        lines.append(f"{sym} {x:.10f} {y:.10f} {z:.10f}")
    lines.append("units angstrom")
    lines.append("no_reorient")
    lines.append("no_com")
    return "\n".join(lines)


def build_mopac_input_text_from_atoms(atoms, keywords="PM7 EF XYZ AUX", total_charge=0, multiplicity=1, title="ProtLigInteract MOPAC job"):
    kw = str(keywords or "PM7 EF XYZ AUX").strip()
    kw_u = kw.upper()
    if "CHARGE=" not in kw_u:
        kw = (kw + f" CHARGE={int(total_charge)}").strip()
    spin_kw = str(_MOPAC_SPIN_LABELS.get(int(max(1, multiplicity)), "")).strip()
    if spin_kw and spin_kw not in kw_u:
        kw = (kw + " " + spin_kw).strip()
    lines = [kw, str(title or "ProtLigInteract MOPAC job"), ""]
    for atom in list(atoms or []):
        sym = str(atom.get("element", atom.get("symbol", "C")) or "C").strip()
        x = _safe_float(atom.get("x", 0.0))
        y = _safe_float(atom.get("y", 0.0))
        z = _safe_float(atom.get("z", 0.0))
        lines.append(f"{sym:2s} {x:14.8f} 1 {y:14.8f} 1 {z:14.8f} 1")
    return "\n".join(lines).rstrip() + "\n"


def _mopac_extract_block_after_key(text, key):
    src = str(text or "")
    k = str(key or "").strip()
    if not k:
        return ""
    pat = (
        rf"(?:^|\n)\s*{re.escape(k)}[^\n=]*=\s*(.*?)"
        rf"(?=\n\s*[A-Z][A-Z0-9_./:\-\(\)\[\]]*[^\n=]*=|\Z)"
    )
    m = re.search(pat, src, flags=re.IGNORECASE | re.DOTALL | re.MULTILINE)
    if not m:
        return ""
    return str(m.group(1) or "")


def _mopac_parse_float_token(token, default=np.nan):
    txt = str(token or "").strip().replace("D", "E").replace("d", "e")
    try:
        val = float(txt)
    except Exception:
        return float(default)
    if not np.isfinite(val):
        return float(default)
    return float(val)


def _mopac_extract_scalar_after_key(text, key, default=np.nan):
    blob = _mopac_extract_block_after_key(text, key)
    if not blob:
        return float(default)
    m = re.search(r"[-+]?\d*\.?\d+(?:[EeDd][-+]?\d+)?", blob)
    if not m:
        return float(default)
    return _mopac_parse_float_token(m.group(0), default=default)


def _mopac_extract_float_vector_after_key(text, key):
    blob = _mopac_extract_block_after_key(text, key)
    if not blob:
        return np.zeros((0,), dtype=float)
    nums = re.findall(r"[-+]?\d*\.?\d+(?:[EeDd][-+]?\d+)?", blob)
    if not nums:
        return np.zeros((0,), dtype=float)
    return np.asarray([_mopac_parse_float_token(x, default=np.nan) for x in nums], dtype=float).reshape(-1)


def _mopac_extract_token_vector_after_key(text, key):
    blob = _mopac_extract_block_after_key(text, key)
    if not blob:
        return []
    return [str(x).strip() for x in str(blob).split() if str(x).strip()]


def parse_mopac_vibrational_aux_text(aux_text):
    txt = str(aux_text or "")
    out = {
        "ok": False,
        "atom_symbols": [],
        "optimized_coords_ang": np.zeros((0, 3), dtype=float),
        "heat_of_formation_kcal_mol": np.nan,
        "zero_point_energy_kcal_mol": np.nan,
        "freq_cm_real": np.zeros((0,), dtype=float),
        "freq_cm_imag": np.zeros((0,), dtype=float),
        "ir_intensity_rel": np.zeros((0,), dtype=float),
        "mode_cart_ang": np.zeros((0, 0, 0), dtype=float),
    }
    symbols = _mopac_extract_token_vector_after_key(txt, "ATOM_EL")
    coords = _mopac_extract_float_vector_after_key(txt, "ATOM_X_OPT:ANGSTROMS")
    if coords.size <= 0:
        coords = _mopac_extract_float_vector_after_key(txt, "ATOM_X:ANGSTROMS")
    nat = 0
    if symbols:
        nat = int(len(symbols))
    elif coords.size >= 3:
        nat = int(coords.size // 3)
    if nat <= 0:
        return out
    coords = coords[: int(nat * 3)]
    if coords.size != int(nat * 3):
        return out
    out["atom_symbols"] = [str(x) for x in list(symbols or [])] if symbols else ["C"] * int(nat)
    out["optimized_coords_ang"] = np.asarray(coords, dtype=float).reshape((nat, 3))
    out["heat_of_formation_kcal_mol"] = _mopac_extract_scalar_after_key(txt, "HEAT_OF_FORMATION:KCAL/MOL", default=np.nan)
    out["zero_point_energy_kcal_mol"] = _mopac_extract_scalar_after_key(txt, "ZERO_POINT_ENERGY:KCAL/MOL", default=np.nan)
    raw_freq = _mopac_extract_float_vector_after_key(txt, "VIB._FREQ:CM(-1)")
    raw_ir = _mopac_extract_float_vector_after_key(txt, "VIB._T_DIP:ELECTRONS")
    raw_modes = _mopac_extract_float_vector_after_key(txt, "NORMAL_MODES")
    n_vib_target = int(max(0, 3 * nat - (5 if nat == 2 else 6)))
    # MOPAC's AUX lists the 3N-6 vibrations first, then the translations/rotations.  Imaginary modes are
    # negative numbers there; they are kept (Psi4 convention: real part 0, magnitude in freq_cm_imag) so
    # that a saddle point is not reported as a minimum with a rotation promoted in its place.
    n_take = int(min(int(raw_freq.size), int(n_vib_target)))
    pos_idx = np.asarray([i for i in range(n_take) if np.isfinite(raw_freq[i])], dtype=int)
    signed = np.asarray(raw_freq[pos_idx], dtype=float).reshape(-1) if pos_idx.size else np.zeros((0,), dtype=float)
    freq_real = np.where(signed < 0.0, 0.0, signed)
    freq_imag = np.where(signed < 0.0, -signed, 0.0)
    # VIB._T_DIP is the transition dipole; the IR intensity goes as its square (as |dmu|^2 on the MM side)
    ir_rel = np.square(np.asarray(raw_ir[pos_idx], dtype=float).reshape(-1)) if (pos_idx.size and raw_ir.size > int(np.max(pos_idx))) else np.zeros((freq_real.size,), dtype=float)
    mode_cart = np.zeros((0, 0, 0), dtype=float)
    ncart = int(3 * nat)
    if int(raw_modes.size) >= int(ncart * ncart) and pos_idx.size:
        mat = np.asarray(raw_modes[: int(ncart * ncart)], dtype=float).reshape((ncart, ncart))
        picked = []
        for idx in list(pos_idx):
            col = np.asarray(mat[int(idx), :], dtype=float).reshape((nat, 3))   # one mode per AUX row
            picked.append(col)
        if picked:
            mode_cart = np.asarray(picked, dtype=float)
    out["freq_cm_real"] = freq_real
    out["freq_cm_imag"] = freq_imag
    out["ir_intensity_rel"] = ir_rel
    out["mode_cart_ang"] = mode_cart
    out["ok"] = bool(freq_real.size > 0)
    return out


def _run_mopac_job_from_atoms(
    atoms,
    out_dir,
    method="PM7",
    mode="optimize",
    charge=0,
    multiplicity=1,
    mopac_executable="mopac",
    timeout_s=3600,
):
    _ensure_dir(out_dir)
    mode_key = str(mode or "optimize").strip().lower()
    base = "mopac_force" if mode_key == "force" else "mopac_opt"
    if mode_key == "force":
        keywords = f"{str(method).upper()} FORCE AUX XYZ"
    else:
        keywords = f"{str(method).upper()} EF AUX XYZ"
    mop_path = os.path.join(out_dir, f"{base}.mop")
    with open(mop_path, "w", encoding="utf-8") as fh:
        fh.write(
            build_mopac_input_text_from_atoms(
                atoms=atoms,
                keywords=keywords,
                total_charge=int(charge),
                multiplicity=int(max(1, multiplicity)),
                title=f"ProtLigInteract {base}",
            )
        )
    proc = subprocess.run(
        [str(mopac_executable), os.path.basename(mop_path)],
        cwd=str(out_dir),
        text=True,
        capture_output=True,
        check=False,
        timeout=int(max(30, timeout_s)),
    )
    if int(proc.returncode) != 0:
        raise RuntimeError(
            f"MOPAC execution failed (rc={int(proc.returncode)}): "
            f"{str(proc.stderr or '')[-1000:]}"
        )
    aux_path = os.path.join(out_dir, f"{base}.aux")
    out_path = os.path.join(out_dir, f"{base}.out")
    if not os.path.isfile(aux_path):
        cand = [x for x in os.listdir(out_dir) if str(x).lower().endswith(".aux")]
        if cand:
            aux_path = os.path.join(out_dir, str(cand[0]))
    if not os.path.isfile(aux_path):
        raise RuntimeError("MOPAC finished but did not produce an AUX file.")
    aux_text = open(aux_path, "r", encoding="utf-8", errors="ignore").read()
    out_text = open(out_path, "r", encoding="utf-8", errors="ignore").read() if os.path.isfile(out_path) else ""
    parsed = parse_mopac_vibrational_aux_text(aux_text)
    if not bool(parsed.get("atom_symbols", [])):
        raise RuntimeError("MOPAC AUX parse failed to recover optimized geometry.")
    return {
        "ok": True,
        "mode": str(mode_key),
        "method": str(method).upper(),
        "aux_file": str(aux_path),
        "out_file": str(out_path),
        "stdout": str(proc.stdout or ""),
        "stderr": str(proc.stderr or ""),
        "parsed": parsed,
        "aux_text": aux_text,
        "out_text": out_text,
    }


