def _compute_state(context):
    _, _, unit = _load_openmm()
    state = context.getState(getPositions=True, getForces=True, getEnergy=True)
    positions = np.asarray(state.getPositions(asNumpy=True).value_in_unit(unit.nanometer), dtype=float)
    forces = np.asarray(
        state.getForces(asNumpy=True).value_in_unit(unit.kilojoule_per_mole / unit.nanometer),
        dtype=float,
    )
    energy = float(state.getPotentialEnergy().value_in_unit(unit.kilojoule_per_mole))
    return positions, forces, energy


def _numerical_hessian(context, coords_nm, step_nm=1.0e-4):
    flat = np.asarray(coords_nm, dtype=float).reshape(-1)
    ncoord = int(flat.size)
    hess = np.zeros((ncoord, ncoord), dtype=float)
    for j in range(ncoord):
        xp = np.array(flat, copy=True)
        xm = np.array(flat, copy=True)
        xp[j] += float(step_nm)
        xm[j] -= float(step_nm)
        context.setPositions(xp.reshape((-1, 3)))
        _, fp, _ = _compute_state(context)
        context.setPositions(xm.reshape((-1, 3)))
        _, fm, _ = _compute_state(context)
        hess[:, j] = (-(fp.reshape(-1) - fm.reshape(-1)) / (2.0 * float(step_nm)))
    context.setPositions(coords_nm.reshape((-1, 3)))
    return 0.5 * (hess + hess.T)


def _mass_weighted_modes_from_hessian(hessian_kjmol_nm2, masses_da):
    masses = np.asarray(masses_da, dtype=float).reshape(-1)
    if masses.size * 3 != int(hessian_kjmol_nm2.shape[0]):
        raise ValueError("Mass / Hessian size mismatch")
    mass_coord = np.repeat(masses, 3)
    mass_kg = mass_coord * 1.66053906660e-27
    h_si = np.asarray(hessian_kjmol_nm2, dtype=float) * (1000.0 / AVOGADRO) * 1.0e18
    denom = np.sqrt(np.outer(mass_kg, mass_kg))
    hw = h_si / denom
    evals, evecs = np.linalg.eigh(hw)
    freq = np.zeros((evals.size,), dtype=float)
    for i, lam in enumerate(np.asarray(evals, dtype=float)):
        mag = math.sqrt(abs(float(lam)))
        cm = mag / (2.0 * math.pi * LIGHT_CM_S)
        freq[i] = -cm if lam < 0.0 else cm
    return freq, evecs


def _cartesian_modes_from_mass_weighted(evecs, masses_da):
    masses = np.asarray(masses_da, dtype=float).reshape(-1)
    mass_coord = np.repeat(masses, 3)
    cart = np.asarray(evecs, dtype=float) / np.sqrt(mass_coord[:, None])
    return cart


def _mode_intensities_from_charges(cart_modes, charges_e):
    q = np.asarray(charges_e, dtype=float).reshape(-1)
    cart = np.asarray(cart_modes, dtype=float)
    nat = int(q.size)
    nmode = int(cart.shape[1])
    intensities = np.zeros((nmode,), dtype=float)
    for i in range(nmode):
        vec = cart[:, i].reshape((nat, 3))
        norm = float(np.linalg.norm(vec))
        if norm > 1.0e-12:
            vec = vec / norm
        dip = np.sum(q[:, None] * vec, axis=0)
        intensities[i] = float(np.dot(dip, dip))
    return intensities


def _kabsch_rmsd(coords_a, coords_b):
    a = np.asarray(coords_a, dtype=float)
    b = np.asarray(coords_b, dtype=float)
    if a.shape != b.shape or a.ndim != 2 or a.shape[1] != 3:
        return float("nan")
    ac = a - np.mean(a, axis=0, keepdims=True)
    bc = b - np.mean(b, axis=0, keepdims=True)
    cov = np.dot(ac.T, bc)
    u, _, vt = np.linalg.svd(cov)
    d = np.linalg.det(np.dot(vt.T, u.T))
    corr = np.diag([1.0, 1.0, -1.0 if d < 0.0 else 1.0])
    rot = np.dot(np.dot(vt.T, corr), u.T)
    aligned = np.dot(ac, rot.T)
    diff = aligned - bc
    return float(np.sqrt(np.mean(np.sum(diff * diff, axis=1))))


def _gaussian_spectrum(freq_cm, intensity, x_grid, fwhm_cm=18.0):
    x = np.asarray(freq_cm, dtype=float).reshape(-1)
    y = np.asarray(intensity, dtype=float).reshape(-1)
    grid = np.asarray(x_grid, dtype=float).reshape(-1)
    if x.size == 0 or y.size == 0 or grid.size == 0:
        return np.zeros_like(grid, dtype=float)
    sigma = float(max(1.0, fwhm_cm)) / float(2.0 * np.sqrt(2.0 * np.log(2.0)))
    out = np.zeros_like(grid, dtype=float)
    for f, amp in zip(x, y):
        out += float(max(0.0, amp)) * np.exp(-0.5 * ((grid - float(f)) / sigma) ** 2)
    if np.max(out) > 1.0e-12:
        out = out / np.max(out)
    return out


def _pearson(x, y):
    xv = np.asarray(x, dtype=float).reshape(-1)
    yv = np.asarray(y, dtype=float).reshape(-1)
    n = int(min(xv.size, yv.size))
    if n <= 1:
        return float("nan")
    xv = xv[:n]
    yv = yv[:n]
    if np.std(xv) < 1.0e-12 or np.std(yv) < 1.0e-12:
        return float("nan")
    return float(np.corrcoef(xv, yv)[0, 1])


def _mode_subset_qm(vib_data):
    freq = np.asarray(vib_data.get("freq_real", []), dtype=float).reshape(-1)
    imag = np.asarray(vib_data.get("freq_imag", []), dtype=float).reshape(-1)
    ir = np.asarray(vib_data.get("ir", []), dtype=float).reshape(-1)
    trv = np.asarray(vib_data.get("trv", []), dtype=object).reshape(-1)
    idx = np.arange(freq.size, dtype=int)
    valid = np.isfinite(freq)
    if imag.size >= freq.size:
        valid &= np.abs(imag[: freq.size]) < 1.0e-3
    if trv.size >= freq.size:
        valid &= np.array([str(trv[i]).upper().startswith("V") for i in range(freq.size)], dtype=bool)
    valid &= np.abs(freq) > 5.0
    ii = idx[valid]
    return {
        "mode_indices": ii,
        "freq_cm": np.asarray(freq[ii], dtype=float),
        "ir_km_mol": np.asarray(ir[ii], dtype=float) if ir.size >= ii.size else np.zeros((ii.size,), dtype=float),
    }


def _mode_subset_mm(freq_cm, intensities, n_keep):
    freq = np.asarray(freq_cm, dtype=float).reshape(-1)
    inten = np.asarray(intensities, dtype=float).reshape(-1)
    if freq.size == 0:
        return {
            "mode_indices": np.array([], dtype=int),
            "freq_cm": np.array([], dtype=float),
            "ir_rel": np.array([], dtype=float),
            "imaginary_count": 0,
        }
    order = np.argsort(np.abs(freq))
    nkeep = int(max(0, min(freq.size, n_keep)))
    pick = order[-nkeep:] if nkeep > 0 else np.array([], dtype=int)
    pick = np.sort(pick)
    return {
        "mode_indices": np.asarray(pick, dtype=int),
        "freq_cm": np.asarray(freq[pick], dtype=float),
        "ir_rel": np.asarray(inten[pick], dtype=float),
        "imaginary_count": int(np.sum(freq[pick] < -5.0)),
    }


def compute_mode_fit_metrics(qm_vib_data, mm_freq_cm, mm_intensity_rel, mm_coords_ang, qm_coords_ang, reg_penalty=0.0):
    qm = _mode_subset_qm(qm_vib_data)
