def qm_result_matches_stage(result, method="", basis="", require_frequency=False):
    res = dict(result or {})
    if not bool(res.get("ok", False)):
        return False
    if method and str(res.get("method", "")) != str(method):
        return False
    if basis and str(res.get("basis", "")) != str(basis):
        return False
    if not str(res.get("optimized_xyz", "") or "").strip():
        return False
    if not require_frequency:
        return True
    if str(res.get("vib_modes_npz", "") or "").strip():
        return True
    return bool(list(res.get("freq_cm_real", []) or []))


def _normalize_qm_stage_key(method, basis):
    m = re.sub(r"\s+", "", str(method or "").strip().lower())
    b = re.sub(r"\s+", "", str(basis or "").strip().lower())
    return (m, b)


def build_qm_optimization_stages(
    target_method,
    target_basis,
    low_method="hf",
    low_basis="sto-3g",
    medium_method="b3lyp",
    medium_basis="6-31g(d)",
    staging_mode="auto",
):
    mode = str(staging_mode or "auto").strip().lower()
    if mode == "off":
        return [{"label": "high", "method": str(target_method), "basis": str(target_basis)}]
    raw = [
        ("low", low_method, low_basis),
        ("medium", medium_method, medium_basis),
        ("high", target_method, target_basis),
    ]
    out = []
    seen = set()
    for label, method, basis in raw:
        key = _normalize_qm_stage_key(method, basis)
        if (not key[0]) or (not key[1]) or (key in seen):
            continue
        seen.add(key)
        out.append({"label": str(label), "method": str(method), "basis": str(basis)})
    return out


def _run_psi4_stationary_from_atoms(
    atoms,
    out_dir,
    method="wb97x-d",
    basis="def2-SVP",
    charge=0,
    multiplicity=1,
    threads=2,
    memory_gb=4,
    run_frequency=True,
    geom_maxiter=120,
):
    import psi4

    atom_rows = list(atoms or [])
    if not atom_rows:
        raise ValueError("No atoms were provided for Psi4 job")
    molecule_block = build_psi4_molecule_block_from_atoms(atom_rows, charge=int(charge), multiplicity=int(max(1, multiplicity)))
    result = {"ok": False, "operation": "stationary" if bool(run_frequency) else "optimize_only"}
    out_dir = os.path.abspath(str(out_dir))      # the result file is written after chdir(out_dir)
    cwd_prev = os.getcwd()
    try:
        _ensure_dir(out_dir)
        os.chdir(out_dir)
        psi4.core.clean()
        # options persist in the process: a previous stage's reference or Cartesian retry must not leak in
        psi4.core.clean_options()
        psi4.set_memory(f"{int(max(1, memory_gb))} GB")
        psi4.set_num_threads(int(max(1, threads)))
        psi4.core.set_output_file("psi4_run.out", False)
        psi4.geometry(molecule_block)

        def _set_opt_options(cartesian=False):
            opts = {
                "basis": str(basis),
                "scf_type": "df",
                "maxiter": 200,
                "geom_maxiter": int(max(20, geom_maxiter)),
                "e_convergence": 1.0e-8,
                "d_convergence": 1.0e-8,
                "write_trajectory": True,
            }
            # Psi4's default RHF/RKS stops on any non-singlet ("RHF reference is only for singlets")
            reference = psi4_reference_for_multiplicity(method, multiplicity=int(max(1, multiplicity)))
            if reference:
                opts["reference"] = reference
            if bool(cartesian):
                # Retry flat/problematic systems in Cartesian coordinates if redundant internals fail.
                opts["opt_coordinates"] = "cartesian"
            psi4.set_options(opts)

        def _is_optking_matrix_failure(exc):
            txt = str(exc or "").lower()
            return ("symmmatrixinv: could not compute eigenvectors" in txt) or ("svd did not converge" in txt)

        _set_opt_options(cartesian=False)
        try:
            ret = psi4.optimize(str(method), return_wfn=True, return_history=True)
            opt_retry_mode = ""
        except Exception as exc:
            if not _is_optking_matrix_failure(exc):
                raise
            psi4.core.clean_options()
            psi4.geometry(molecule_block)
            psi4.core.set_output_file("psi4_run.out", True)
            _set_opt_options(cartesian=True)
            ret = psi4.optimize(str(method), return_wfn=True, return_history=True)
            opt_retry_mode = "cartesian_after_optking_matrix_failure"
        eopt, wopt, opt_hist = _parse_opt_return(ret)
        result["energy_opt_hartree"] = float(eopt)
        if opt_retry_mode:
            result["opt_retry_mode"] = str(opt_retry_mode)
        mol_fin = psi4.core.get_active_molecule()
        mol_fin.update_geometry()
        nat = int(mol_fin.natom())
        symbols = [str(mol_fin.symbol(i)).strip() for i in range(nat)]
        bohr_fin = _mat_to_array_bohr(mol_fin.geometry(), nat)
        ang_fin = bohr_fin * float(psi4.constants.bohr2angstroms)
        _write_xyz("optimized.xyz", symbols, ang_fin, comment="Optimized geometry from ProtLigInteract")
        result["optimized_xyz"] = "optimized.xyz"
        result["atom_symbols"] = [str(s) for s in symbols]
        if isinstance(opt_hist, dict):
            hist_e = np.asarray(opt_hist.get("energy", []), dtype=float).reshape(-1)
            hist_c = np.asarray(opt_hist.get("coordinates", []), dtype=float)
            if hist_c.ndim == 3 and hist_c.shape[1] == nat and hist_c.shape[2] == 3:
                hist_ang = hist_c * float(psi4.constants.bohr2angstroms)
                nkeep = int(min(hist_ang.shape[0], hist_e.size)) if hist_e.size else int(hist_ang.shape[0])
                if nkeep > 0:
                    hist_ang = hist_ang[:nkeep]
                    hist_e = hist_e[:nkeep] if hist_e.size else np.zeros((nkeep,), dtype=float)
                    np.savez_compressed(
                        "history_data.npz",
                        coords_ang=hist_ang.astype(np.float32),
                        energy_hartree=hist_e.astype(float),
                        atom_symbols=np.asarray(symbols, dtype="U4"),
                    )
                    result["history_npz"] = "history_data.npz"
                    result["history_energy_hartree"] = [float(v) for v in hist_e.tolist()]
        result["energy_freq_hartree"] = None
        result["thermo"] = {}
        if bool(run_frequency):
            efreq, wfn_freq = psi4.frequency(str(method), return_wfn=True)
            result["energy_freq_hartree"] = float(efreq)
            result["thermo"] = _collect_thermo_psivars(psi4)
            freq_payload = _collect_frequency_payload(psi4, wfn_freq, nat)
            if freq_payload:
                result["freq_cm_real"] = [float(v) for v in freq_payload.get("freq_cm_real", [])]
                result["freq_cm_imag"] = [float(v) for v in freq_payload.get("freq_cm_imag", [])]
                result["ir_intensity_km_mol"] = [float(v) for v in freq_payload.get("ir_intensity_km_mol", [])]
                result["freq_trv"] = [str(v) for v in freq_payload.get("freq_trv", [])]
                mode_cart = freq_payload.get("_mode_cart_ang")
                if mode_cart is not None:
                    mc = np.asarray(mode_cart, dtype=float)
                    if mc.ndim == 3 and mc.shape[1] == nat and mc.shape[2] == 3:
                        np.savez_compressed(
                            "vib_modes.npz",
                            mode_cart_ang=mc.astype(np.float32),
                            eq_geom_ang=ang_fin.astype(np.float32),
                            atom_symbols=np.asarray(symbols, dtype="U4"),
                            freq_cm_real=np.asarray(result.get("freq_cm_real", []), dtype=float),
                            freq_cm_imag=np.asarray(result.get("freq_cm_imag", []), dtype=float),
                            ir_intensity_km_mol=np.asarray(result.get("ir_intensity_km_mol", []), dtype=float),
                            trv=np.asarray(result.get("freq_trv", []), dtype="U12"),
                        )
                        result["vib_modes_npz"] = "vib_modes.npz"
            fr = np.asarray(result.get("freq_cm_real", []), dtype=float).reshape(-1)
            fi = np.asarray(result.get("freq_cm_imag", []), dtype=float).reshape(-1)
            ii = np.asarray(result.get("ir_intensity_km_mol", []), dtype=float).reshape(-1)
            tr = np.asarray(result.get("freq_trv", []), dtype=object).reshape(-1)
            nrow = int(min(fr.size, ii.size))
            with open("ir_spectrum.csv", "w", encoding="utf-8", newline="") as fh:
                writer = csv.writer(fh)
                writer.writerow(["mode", "frequency_cm-1", "imag_cm-1", "ir_km_mol", "trv"])
                for i in range(nrow):
                    imag = float(fi[i]) if i < fi.size else 0.0
                    trv = str(tr[i]) if i < tr.size else ""
                    writer.writerow([int(i + 1), float(fr[i]), imag, float(ii[i]), trv])
            result["ir_spectrum_csv"] = "ir_spectrum.csv"
        result["charge"] = int(charge)
        result["multiplicity"] = int(max(1, multiplicity))
        result["method"] = str(method)
        result["basis"] = str(basis)
        result["ok"] = True
    except Exception as exc:
        result["error"] = str(exc)
        result["traceback"] = traceback.format_exc()
    finally:
        with open(os.path.join(out_dir, "psi4_result.json"), "w", encoding="utf-8") as fh:
            json.dump(result, fh, indent=2)
        os.chdir(cwd_prev)
    return result


