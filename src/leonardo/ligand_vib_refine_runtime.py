def _infer_element_from_mol2_name_type(atom_name, atom_type):
    name = str(atom_name or "").strip()
    atype = str(atom_type or "").strip()
    name_letters = re.sub(r"[^A-Za-z]", "", name)
    if name_letters:
        if len(name_letters) >= 2 and name_letters[:2].upper() in _MOL2_TWO_LETTER_ELEMENTS:
            return str(name_letters[:2].capitalize())
        return str(name_letters[:1].upper())
    at_low = atype.lower()
    if at_low[:2] in ("cl", "br"):
        return str(at_low[:2].capitalize())
    if at_low[:2] in ("si", "na", "mg", "zn", "fe", "cu", "mn", "co", "ni", "al", "li", "se"):
        return str(at_low[:2].capitalize())
    if at_low[:1] in _GAFF_ELEMENT_BY_PREFIX:
        return str(_GAFF_ELEMENT_BY_PREFIX[at_low[:1]])
    return "C"


def _mat_to_array_bohr(mat, n):
    arr = np.zeros((int(n), 3), dtype=float)
    for i in range(int(n)):
        for j in range(3):
            try:
                arr[i, j] = float(mat.get(i, j))
            except Exception:
                arr[i, j] = float(np.asarray(mat)[i, j])
    return arr


def _write_xyz(path, symbols, coords_ang, comment="Generated by ProtLigInteract"):
    coords = np.asarray(coords_ang, dtype=float)
    syms = [str(x) for x in list(symbols or [])]
    nat = int(coords.shape[0])
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(f"{nat}\n")
        fh.write(f"{comment}\n")
        for i in range(nat):
            s = syms[i] if i < len(syms) else "C"
            x, y, z = coords[i]
            fh.write(f"{s} {x:.10f} {y:.10f} {z:.10f}\n")


def _datum_data(d):
    if d is None:
        return None
    try:
        if hasattr(d, "data"):
            return np.asarray(d.data)
        return np.asarray(d)
    except Exception:
        return None


