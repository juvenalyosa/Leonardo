    ref_freq = np.asarray(refined_metrics.get("mm_freq_cm", []), dtype=float).reshape(-1)
    qm_ir = np.asarray(qm_metrics.get("qm_ir_rel", []), dtype=float).reshape(-1)
    base_ir = np.asarray(base_metrics.get("mm_ir_rel", []), dtype=float).reshape(-1)
    ref_ir = np.asarray(refined_metrics.get("mm_ir_rel", []), dtype=float).reshape(-1)
    n = int(min(qm_freq.size, base_freq.size, ref_freq.size))
    rows = []
    for i in range(n):
        rows.append(
            {
                "mode_rank": int(i + 1),
                "qm_freq_cm": float(qm_freq[i]),
                "ff_initial_freq_cm": float(base_freq[i]),
                "ff_refined_freq_cm": float(ref_freq[i]),
                "ff_initial_abs_error_cm": float(abs(base_freq[i] - qm_freq[i])),
                "ff_refined_abs_error_cm": float(abs(ref_freq[i] - qm_freq[i])),
                "qm_ir_rel": float(qm_ir[i]) if i < qm_ir.size else 0.0,
                "ff_initial_ir_rel": float(base_ir[i]) if i < base_ir.size else 0.0,
                "ff_refined_ir_rel": float(ref_ir[i]) if i < ref_ir.size else 0.0,
            }
        )
    return rows


