def _safe_float(value, default=0.0):
    try:
        out = float(value)
    except Exception:
        return float(default)
    if not np.isfinite(out):
        return float(default)
    return float(out)


def _safe_int(value, default=0):
    try:
        return int(value)
    except Exception:
        return int(default)


