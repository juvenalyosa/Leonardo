"""The installer's PyMOL loader must be on PyMOL's plugin path on a computer that never used the Plugin Manager
(PyMOL reads ~/.pymol/startup only when ~/.pymolpluginsrc.py adds it)."""
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _install(home):
    env = dict(os.environ, HOME=str(home), LEONARDO_LOADER_ROOT=ROOT)
    env.pop("PYMOL_STARTUP_DIR", None)
    env.pop("PYMOL_PLUGINSRC", None)
    subprocess.run(["bash", os.path.join(ROOT, "scripts", "install_pymol_loader.sh"), "--quiet"], env=env, check=True)


def test_loader_adds_user_plugin_folder_once(tmp_path):
    _install(tmp_path)
    _install(tmp_path)
    assert (tmp_path / ".pymol" / "startup" / "leonardo.py").is_file()
    rc = (tmp_path / ".pymolpluginsrc.py").read_text()
    assert rc.count("Leonardo: PyMOL's user plugin folder") == 1
    assert "set_startup_path" in rc and "~/.pymol/startup" in rc
    compile(rc, "pluginsrc", "exec")


def test_existing_pluginsrc_is_kept(tmp_path):
    original = "# AUTOGENERATED FILE\ntry:\n  import pymol.plugins\n  pymol.plugins.autoload = {'apbs_gui': False}\nexcept:\n  pass\n"
    (tmp_path / ".pymolpluginsrc.py").write_text(original)
    _install(tmp_path)
    rc = (tmp_path / ".pymolpluginsrc.py").read_text()
    assert rc.startswith(original) and "Leonardo: PyMOL's user plugin folder" in rc
